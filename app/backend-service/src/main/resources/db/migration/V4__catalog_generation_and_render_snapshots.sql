CREATE TABLE media_generation_items (
    id UUID PRIMARY KEY,
    generation_job_id UUID NOT NULL REFERENCES generation_jobs(id) ON DELETE CASCADE,
    media_plan_id UUID NOT NULL REFERENCES media_plans(id),
    visual_beat_id UUID NOT NULL REFERENCES visual_beats(id),
    item_key VARCHAR(160) NOT NULL,
    shot_id UUID,
    order_index INTEGER NOT NULL DEFAULT 0,
    leaf_generation_job_id UUID UNIQUE REFERENCES generation_jobs(id),
    take_id UUID UNIQUE,
    frozen_input_json JSONB,
    frozen_input_fingerprint VARCHAR(64),
    attempt_number INTEGER NOT NULL,
    execution_status VARCHAR(24) NOT NULL,
    provider_operation_id UUID REFERENCES provider_operations(id),
    media_asset_id UUID REFERENCES media_assets(id),
    request_fingerprint VARCHAR(128) NOT NULL,
    error_code VARCHAR(80),
    error_detail_ref VARCHAR(160),
    review_status VARCHAR(24) NOT NULL DEFAULT 'NOT_READY',
    reviewed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    row_version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_media_generation_items_attempt UNIQUE (generation_job_id, item_key, attempt_number),
    CONSTRAINT ck_media_generation_items_leaf_mapping CHECK ((leaf_generation_job_id IS NULL) = (take_id IS NULL)),
    CONSTRAINT ck_media_generation_items_frozen_shot CHECK ((shot_id IS NULL AND frozen_input_json IS NULL AND frozen_input_fingerprint IS NULL) OR
      (shot_id IS NOT NULL AND frozen_input_json IS NOT NULL AND frozen_input_fingerprint ~ '^[0-9a-f]{64}$')),
    CONSTRAINT ck_media_generation_items_attempt CHECK (attempt_number > 0),
    CONSTRAINT ck_media_generation_items_execution_status CHECK (execution_status IN ('QUEUED', 'RUNNING', 'VALIDATING', 'READY', 'FAILED', 'CANCELED', 'UNKNOWN')),
    CONSTRAINT ck_media_generation_items_review_status CHECK (review_status IN ('NOT_READY', 'NEEDS_REVIEW', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_media_generation_items_fingerprint CHECK (request_fingerprint ~ '^[0-9a-f]{64,128}$'),
    CONSTRAINT ck_media_generation_items_review_fields CHECK (
        (review_status IN ('NOT_READY', 'NEEDS_REVIEW') AND reviewed_at IS NULL)
        OR
        (review_status IN ('APPROVED', 'REJECTED') AND reviewed_at IS NOT NULL)
    ),
    CONSTRAINT fk_media_generation_items_shot FOREIGN KEY (shot_id) REFERENCES shots(id),
    CONSTRAINT fk_media_generation_items_take FOREIGN KEY (take_id) REFERENCES takes(id)
);

